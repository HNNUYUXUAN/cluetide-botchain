import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const profile=JSON.parse(fs.readFileSync(path.join(root,'configs/historical-bot677.json'),'utf8'));
const typescript='// Generated by scripts/generate-config.mjs from configs/historical-bot677.json.\nexport const publicConfig = Object.freeze('+JSON.stringify(profile,null,2).replace(/("contract": "0x[0-9a-f]+")/,'$1 as const')+');\n';
for(const [name,contents] of [['frontend/src/release/public-config.ts',typescript],['src/cluetide/resources/historical-bot677.json',JSON.stringify(profile,null,2)+'\n']]){
  const file=path.join(root,name);
  if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8')!==contents)throw Error(name+' differs from deployment configuration');}
  else fs.writeFileSync(file,contents);
}
console.log('Python and TypeScript historical deployment configuration agrees');
